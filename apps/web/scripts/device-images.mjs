// Builds the WebP renditions of the device photos in public/img/devices
// (DOS/Rate#1332). The photos are 800x800 JPEGs shown at 44-175 px; the site
// serves them as they are (images.unoptimized), so the small sizes are made
// here once and committed, with no image optimization at request time.
//
// Each rendition's file name carries a hash of its source photo, so the files
// can be cached as immutable. Run after adding or replacing a photo:
//   node apps/web/scripts/device-images.mjs
import { createHash } from 'node:crypto';
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import sharp from 'sharp';

const webRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(webRoot, 'public/img/devices');
const outDir = join(sourceDir, 'sized');
const manifestFile = join(webRoot, 'src/lib/device-image-renditions.ts');
// Target widths. A photo smaller than a target gets no rendition at that width
// (an upscaled or same-size copy would be listed under a width it does not
// have, and the browser would shrink it); its own width is used instead.
const TARGET_WIDTHS = [200, 400, 600];
const WEBP_QUALITY = 78;

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const entries = [];
for (const file of readdirSync(sourceDir).sort()) {
  const match = /^([a-z0-9-]+)\.jpg$/.exec(file);
  if (!match) continue;
  const slug = match[1];
  const source = readFileSync(join(sourceDir, file));
  const { width: sourceWidth } = await sharp(source).metadata();
  const widths = TARGET_WIDTHS.filter((w) => w < sourceWidth);
  if (widths.length < TARGET_WIDTHS.length) widths.push(sourceWidth);
  // The hash covers the source and the settings, so a changed rendition
  // always gets a new URL (the files are cached as immutable).
  const hash = createHash('sha256')
    .update(source)
    .update(JSON.stringify({ widths, quality: WEBP_QUALITY }))
    .digest('hex')
    .slice(0, 10);
  for (const width of widths) {
    await sharp(source)
      .resize({ width })
      .webp({ quality: WEBP_QUALITY })
      .toFile(join(outDir, `${slug}-${width}.${hash}.webp`));
  }
  entries.push([slug, hash, widths]);
}

const manifest = `// Generated by apps/web/scripts/device-images.mjs. Do not edit by hand.
// Device photo slug -> rendition hash and the widths built (DOS/Rate#1332).
export const DEVICE_IMAGE_RENDITIONS: Readonly<
  Record<string, { readonly hash: string; readonly widths: readonly number[] }>
> = {
${entries.map(([slug, hash, widths]) => `  '${slug}': { hash: '${hash}', widths: [${widths.join(', ')}] },`).join('\n')}
};
`;
writeFileSync(
  manifestFile,
  await format(manifest, {
    ...(await resolveConfig(manifestFile)),
    filepath: manifestFile,
  })
);
console.warn(
  `${entries.length} photos, ${entries.reduce((n, e) => n + e[2].length, 0)} renditions`
);
