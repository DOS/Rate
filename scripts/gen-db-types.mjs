#!/usr/bin/env node
// Generates packages/shared-data/src/database.types.ts for the `rate` schema
// from supabase/migrations: replays them on a throwaway PostgreSQL 17
// (scripts/lib/rate-db.mjs) and asks supabase/postgres-meta, the generator the
// Supabase CLI uses, for the TypeScript types. No real database is touched.
//
// Usage: node scripts/gen-db-types.mjs           (write the file)
//        node scripts/gen-db-types.mjs --check   (fail if it is out of date)
// Needs Docker.

import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import * as prettier from 'prettier';

import { docker, repoRoot, startRateDb } from './lib/rate-db.mjs';

const check = process.argv.includes('--check');
const outFile = path.join(
  repoRoot,
  'packages',
  'shared-data',
  'src',
  'database.types.ts'
);
const META_IMAGE =
  'supabase/postgres-meta:v0.99.0@sha256:9a079ac1c94d89629262822a4bd1902d5b1be4adb464e5a0a8fd078aaed72158';

const id = `rate-db-types-${process.pid}`;
const network = id;
const dbName = `${id}-db`;
const metaName = `${id}-meta`;

function cleanup() {
  spawnSync('docker', ['rm', '--force', metaName, dbName], { timeout: 30_000 });
  spawnSync('docker', ['network', 'rm', network], { timeout: 30_000 });
}
for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => {
    cleanup();
    process.exit(130);
  });
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function generate() {
  docker(['network', 'create', network]);
  startRateDb({
    name: dbName,
    runArgs: ['--network', network, '--network-alias', 'db'],
  });
  docker(
    [
      'run',
      '--detach',
      '--name',
      metaName,
      '--network',
      network,
      '-p',
      '127.0.0.1::8080',
      '-e',
      'PG_META_DB_URL=postgres://postgres:local-test-only@db:5432/postgres',
      META_IMAGE,
    ],
    { timeout: 180_000 }
  );
  const port = Number(
    docker(['port', metaName, '8080/tcp']).split('\n')[0].split(':').pop()
  );
  const url = `http://127.0.0.1:${port}/generators/typescript?included_schemas=rate`;
  const deadline = Date.now() + 60_000;
  for (;;) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(10_000) });
      if (res.ok) return await res.text();
    } catch {
      // not up yet
    }
    if (Date.now() >= deadline) {
      const logs = spawnSync('docker', ['logs', metaName], {
        encoding: 'utf8',
        timeout: 10_000,
      });
      throw new Error(
        `postgres-meta did not answer at ${url}\n${logs.stdout}${logs.stderr}`
      );
    }
    await sleep(500);
  }
}

let exitCode = 1;
try {
  const raw = await generate();
  const header =
    '// Generated by `pnpm gen:db-types` from supabase/migrations. Do not edit by\n' +
    '// hand; CI fails when it drifts from the migrations.\n\n';
  const formatted = await prettier.format(header + raw, {
    ...(await prettier.resolveConfig(outFile)),
    filepath: outFile,
  });
  if (check) {
    let current = '';
    try {
      current = readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n');
    } catch {
      // missing file is drift too
    }
    if (current !== formatted) {
      throw new Error(
        `${path.relative(repoRoot, outFile)} is out of date with supabase/migrations; run \`pnpm gen:db-types\` and commit it`
      );
    }
    console.log('rate schema types match supabase/migrations');
  } else {
    writeFileSync(outFile, formatted);
    console.log(`wrote ${path.relative(repoRoot, outFile)}`);
  }
  exitCode = 0;
} catch (err) {
  console.error(err instanceof Error ? err.message : err);
} finally {
  cleanup();
}
process.exit(exitCode);
